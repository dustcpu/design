# ---------------------------------------------------------------- 采样 / 输出
def sample(stroke, n=30):
    (t0, s0), segs = stroke
    pts = [(t0, s0)]
    cur = (t0, s0)
    for sg in segs:
        if sg[0] == 'L':
            cur = (sg[1], sg[2]); pts.append(cur)
        elif sg[0] == 'Q':
            cx, cy, x, y = sg[1:]
            for i in range(1, n + 1):
                t = i / n
                pts.append(((1 - t) ** 2 * cur[0] + 2 * (1 - t) * t * cx + t * t * x,
                            (1 - t) ** 2 * cur[1] + 2 * (1 - t) * t * cy + t * t * y))
            cur = (x, y)
        else:
            a, b, c, d, x, y = sg[1:]
            for i in range(1, n + 1):
                t = i / n
                pts.append(((1 - t) ** 3 * cur[0] + 3 * (1 - t) ** 2 * t * a + 3 * (1 - t) * t * t * c + t ** 3 * x,
                            (1 - t) ** 3 * cur[1] + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t * t * d + t ** 3 * y))
            cur = (x, y)
    return pts


def to_d(stroke):
    (t0, s0), segs = stroke
    d = "M %.1f %.1f" % (X(t0), Y(s0))
    for sg in segs:
        vals = [X(v) if i % 2 == 0 else Y(v) for i, v in enumerate(sg[1:])]
        d += " " + sg[0] + " " + " ".join("%.1f" % v for v in vals)
    return d


def draw_glyph(dr, strokes, ox, oy, size, w=STROKE_W, fill=(31, 77, 56)):
    k = size / 1000.0
    lw = max(1, int(round(w * k)))
    for st in strokes:
        pts = [(ox + X(p[0]) * k, oy + Y(p[1]) * k) for p in sample(st)]
        for i in range(len(pts) - 1):
            dr.line([pts[i], pts[i + 1]], fill=fill, width=lw, joint="curve")
        r = lw / 2.0
        for p in (pts[0], pts[-1]):
            dr.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=fill)


def glyph_image(strokes, size, ss=4, fill=(31, 77, 56), bg=(255, 255, 255)):
    """超采样渲染（Pillow 折线拼接在粗线下会有毛刺，放大画再缩回即平滑）"""
    big = Image.new('RGB', (size * ss, size * ss), bg)
    draw_glyph(ImageDraw.Draw(big), strokes, 0, 0, size * ss, STROKE_W, fill)
    return big.resize((size, size), Image.LANCZOS)


def glyph_mask(strokes, size, ss=4):
    big = Image.new('L', (size * ss, size * ss), 0)
    draw_glyph(ImageDraw.Draw(big), strokes, 0, 0, size * ss, STROKE_W, 255)
    return big.resize((size, size), Image.LANCZOS).point(lambda v: 255 if v > 128 else 0)


