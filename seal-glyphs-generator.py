# 字形盒子：x 200..800（宽 600），y 50..950（高 900） → 1 : 1.5，标准小篆竖长
GX, GY, GW, GH = 200.0, 50.0, 600.0, 900.0
def X(t): return GX + GW * t
def Y(s): return GY + GH * s

STROKE_W = 60          # 笔画宽度（相对 1000 画布），≈ 字宽 10%


# ---------------------------------------------------------------- 基础 DSL
def S(t, s, *segs):
    """一笔：起点 (t,s) + 若干段 ('L',t,s) / ('Q',ct,cs,t,s) / ('C',c1..,t,s)"""
    return ((t, s), segs)


def H(t0, t1, s, bow=0.020):
    """横线：两端严格同高（消除歪斜），中间微拱出弹性"""
    return S(t0, s, ('Q', (t0 + t1) / 2.0, s - bow, t1, s))


def V(t, s0, s1, bend=0.0):
    """竖线：严格垂直"""
    if not bend:
        return S(t, s0, ('L', t, s1))
    return S(t, s0, ('Q', t + bend, (s0 + s1) / 2.0, t, s1))


def PIE(t0, s0, t1, s1, k=1.0):
    """撇/捺垂脚：起笔近乎垂直下行，末端才向外弯出（篆书垂脚走势）"""
    dt, ds = (t1 - t0) * k, (s1 - s0) * k
    return S(t0, s0, ('C', t0 + dt * 0.05, s0 + ds * 0.45,
                      t0 + dt * 0.40, s0 + ds * 0.76,
                      t0 + dt, s0 + ds))


def mir(stroke, ax=0.5):
    """沿纵轴 t=ax 镜像一笔（控制点反序），机器级对称"""
    (t0, s0), segs = stroke
    def mx(x): return 2.0 * ax - x
    nodes = [(t0, s0)]
    ctrls = []
    for sg in segs:
        if sg[0] == 'L':
            nodes.append((sg[1], sg[2])); ctrls.append([])
        elif sg[0] == 'Q':
            nodes.append((sg[3], sg[4])); ctrls.append([(sg[1], sg[2])])
        else:
            nodes.append((sg[5], sg[6])); ctrls.append([(sg[1], sg[2]), (sg[3], sg[4])])
    start = (mx(nodes[-1][0]), nodes[-1][1])
    out = []
    for i in range(len(segs) - 1, -1, -1):
        cmd = segs[i][0]
        ex, ey = mx(nodes[i][0]), nodes[i][1]
        cs = [(mx(p[0]), p[1]) for p in reversed(ctrls[i])]
        if cmd == 'L':
            out.append(('L', ex, ey))
        elif cmd == 'Q':
            out.append(('Q', cs[0][0], cs[0][1], ex, ey))
        else:
            out.append(('C', cs[0][0], cs[0][1], cs[1][0], cs[1][1], ex, ey))
    return (start, tuple(out))


def pair(stroke, ax=0.5):
    return [stroke, mir(stroke, ax)]


