"""仿篆书字形 v2 —— 简体结构 + 小篆法度。

法度四条：
 1. 中轴：左右同构的部件一律「写一半 + 程序镜像」，机器保证严格对称
 2. 等距：平行笔画落在统一纵/横网格上，白距均匀（计白当黑）
 3. 等粗：所有笔画同宽（约字宽 9.5%），端点圆头
 4. 圆转：所有转折用 Q/C 圆弧，杜绝尖角；字格竖长 2:3，尽量满格

坐标全部用 0..1 的「字格相对坐标」(t, s)，t 是横向、s 是纵向。
镜像在相对坐标上完成，最后统一映射到 1000x1000 画布。
"""
